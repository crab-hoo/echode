//! Generate the Swift edit boundary from the authoritative action catalog.
//!
//! Run with no arguments to print, `--write PATH` to regenerate, or `--check PATH` to verify.
//! Unknown schema shapes fail closed instead of weakening the Swift boundary.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

use echode_actions::{ActionSpec, catalog};
use serde_json::Value;

type Result<T> = std::result::Result<T, String>;

#[derive(Debug)]
struct Field {
    wire: String,
    swift: String,
    kind: &'static str,
    optional: bool,
}

fn identifier(wire: &str) -> Result<String> {
    let mut words = wire.split('_');
    let mut result = words.next().unwrap_or_default().to_string();
    for word in words {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            result.extend(first.to_uppercase());
            result.extend(chars);
        }
    }
    if !result.starts_with(|c: char| c.is_ascii_alphabetic())
        || !result.chars().all(|c| c.is_ascii_alphanumeric())
    {
        return Err(format!("unsupported Swift identifier: {wire}"));
    }
    // Backticks also cover future Swift keywords without another keyword list.
    Ok(format!("`{result}`"))
}

fn field(wire: &str, schema: &Value, required: bool) -> Result<Field> {
    let object = schema.as_object().ok_or("field schema is not an object")?;
    for key in object.keys() {
        if !matches!(
            key.as_str(),
            "type" | "format" | "minimum" | "maximum" | "default" | "description" | "title"
        ) {
            return Err(format!("unsupported schema keyword for {wire}: {key}"));
        }
    }
    let (kind, nullable) = match &schema["type"] {
        Value::String(kind) => (kind.as_str(), false),
        Value::Array(types) if types.len() == 2 && types[1] == "null" => {
            (types[0].as_str().ok_or("invalid nullable type")?, true)
        }
        _ => return Err(format!("unsupported schema type for {wire}")),
    };
    let format = schema.get("format").and_then(Value::as_str);
    let kind = match (kind, format) {
        // Rust resolves result references for any string field, so all share `Text`.
        ("string", None) => "Text",
        ("boolean", None) => "Bool",
        ("integer", None | Some("int64")) => "Int64",
        ("integer", Some("uint8")) => "UInt8",
        ("integer", Some("uint16")) => "UInt16",
        ("integer", Some("uint32")) => "UInt32",
        ("integer", Some("uint64")) => "UInt64",
        ("number", Some("float")) => "Float",
        _ => {
            return Err(format!(
                "unsupported schema format for {wire}: {kind}/{format:?}"
            ));
        }
    };
    if !required && !nullable {
        return Err(format!("unsupported non-nullable default for {wire}"));
    }
    Ok(Field {
        wire: wire.into(),
        swift: identifier(wire)?,
        kind,
        optional: nullable,
    })
}

fn fields(schema: &Value) -> Result<Vec<Field>> {
    for key in schema
        .as_object()
        .ok_or("action schema is not an object")?
        .keys()
    {
        if !matches!(
            key.as_str(),
            "$schema" | "title" | "description" | "type" | "properties" | "required"
        ) {
            return Err(format!("unsupported action schema keyword: {key}"));
        }
    }
    if schema["type"] != "object" {
        return Err("action schema is not an object".into());
    }
    let required = schema["required"]
        .as_array()
        .ok_or("missing required fields")?;
    let properties = schema["properties"]
        .as_object()
        .ok_or("missing properties")?;
    // Use the schema's required order, then optional fields in lexical order.
    let mut names = Vec::new();
    for name in required {
        let name = name.as_str().ok_or("invalid required field")?;
        if !properties.contains_key(name) || names.contains(&name) {
            return Err(format!("invalid required field: {name}"));
        }
        names.push(name);
    }
    for name in properties.keys() {
        if !names.contains(&name.as_str()) {
            names.push(name);
        }
    }
    let result: Vec<_> = names
        .into_iter()
        .filter(|name| *name != "type")
        .map(|name| field(name, &properties[name], required.iter().any(|v| v == name)))
        .collect::<Result<_>>()?;
    let mut seen = BTreeSet::new();
    for field in &result {
        if !seen.insert(&field.swift) {
            return Err(format!("duplicate Swift field: {}", field.swift));
        }
    }
    Ok(result)
}

fn generate(actions: &[ActionSpec]) -> Result<String> {
    let mut result = String::from(
        "// Generated by echode-actions/examples/swift_actions.rs. Do not edit.\n\
         // Regenerate with `make swift-actions`; verify with `make check-swift-actions`.\n\
         import Foundation\n\n\
         /// Typed action requests with literal strings.\n\
         public typealias EditAction = EditActionOf<String>\n\n\
         /// A transaction whose strings may name results of its earlier actions.\n\
         public typealias ReferencingEditAction = EditActionOf<EditText>\n\n\
         /// Typed action requests. Rust still validates model constraints and references.\n\
         public enum EditActionOf<Text: Encodable & Sendable>: Encodable, Sendable {\n",
    );
    let mut entries = Vec::new();
    let mut seen = BTreeSet::new();
    for action in actions {
        let schema = action.schema();
        if schema["properties"]["type"]["const"] != action.id {
            return Err(format!("action tag mismatch: {}", action.id));
        }
        let title = schema["title"].as_str().ok_or("missing action title")?;
        let mut name = title.to_string();
        if !name.is_ascii() || name.is_empty() {
            return Err(format!("unsupported action title: {title}"));
        }
        name[..1].make_ascii_lowercase();
        let name = identifier(&name)?;
        if !seen.insert(name.clone()) {
            return Err(format!("duplicate Swift action: {name}"));
        }
        let fields = fields(&schema)?;
        let arguments = fields
            .iter()
            .map(|f| {
                format!(
                    "{}: {}{}{}",
                    f.swift,
                    f.kind,
                    if f.optional { "?" } else { "" },
                    if f.optional { " = nil" } else { "" }
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(result, "    case {name}({arguments})").unwrap();
        entries.push((action.id, name, fields));
    }
    result.push_str(
        r#"
    private struct Key: CodingKey {
        let stringValue: String
        var intValue: Int? { nil }
        init(_ value: String) { stringValue = value }
        init?(stringValue: String) { self.init(stringValue) }
        init?(intValue: Int) { return nil }
    }

    public func encode(to encoder: any Encoder) throws {
        var object = encoder.container(keyedBy: Key.self)
        switch self {
"#,
    );
    for (id, name, fields) in entries {
        let bindings = fields
            .iter()
            .map(|f| f.swift.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(result, "        case let .{name}({bindings}):").unwrap();
        writeln!(
            result,
            "            try object.encode(\"{id}\", forKey: Key(\"type\"))"
        )
        .unwrap();
        for f in fields {
            // Explicit null retains Option semantics, including removing a parent/state.
            writeln!(
                result,
                "            try object.encode({}, forKey: Key(\"{}\"))",
                f.swift, f.wire
            )
            .unwrap();
        }
    }
    result.push_str("        }\n    }\n}\n");
    Ok(result)
}

fn check(path: &Path, expected: &str) -> Result<()> {
    let actual = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    if actual != expected {
        return Err(format!(
            "{} is stale; run make swift-actions",
            path.display()
        ));
    }
    Ok(())
}

fn run() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let output = generate(catalog())?;
    match args.as_slice() {
        [] => {
            print!("{output}");
            Ok(())
        }
        [flag, path] if flag == "--check" => check(Path::new(path), &output),
        [flag, path] if flag == "--write" => {
            if std::fs::read_to_string(path).ok().as_deref() != Some(&output) {
                std::fs::write(path, output).map_err(|e| format!("{path}: {e}"))?;
            }
            Ok(())
        }
        _ => Err("usage: swift_actions [--check PATH | --write PATH]".into()),
    }
}

fn main() -> std::process::ExitCode {
    match run() {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("swift-actions: {error}");
            std::process::ExitCode::FAILURE
        }
    }
}

